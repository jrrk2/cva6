// keccak_round.sv — Single round of Keccak-f[1600] (combinational)
//
// Keccak spec: flat bit index of lane(x,y) = (5*y + x) * 64
// Lane naming: sXY where X=x, Y=y

module keccak_round
  import keccak_pkg::*;
(
  input  logic [1599:0] state_in,
  input  logic [4:0]    round_idx,
  output logic [1599:0] state_out
);

  // ----------------------------------------------------------------
  //  Extract input lanes: flat idx = 5*y + x
  //  idx  0=(0,0)  1=(1,0)  2=(2,0)  3=(3,0)  4=(4,0)
  //  idx  5=(0,1)  6=(1,1)  7=(2,1)  8=(3,1)  9=(4,1)
  //  idx 10=(0,2) 11=(1,2) 12=(2,2) 13=(3,2) 14=(4,2)
  //  idx 15=(0,3) 16=(1,3) 17=(2,3) 18=(3,3) 19=(4,3)
  //  idx 20=(0,4) 21=(1,4) 22=(2,4) 23=(3,4) 24=(4,4)
  // ----------------------------------------------------------------
  // s{x}{y}
  wire [63:0] s00 = state_in[   63:   0];  // idx 0
  wire [63:0] s10 = state_in[  127:  64];  // idx 1
  wire [63:0] s20 = state_in[  191: 128];  // idx 2
  wire [63:0] s30 = state_in[  255: 192];  // idx 3
  wire [63:0] s40 = state_in[  319: 256];  // idx 4
  wire [63:0] s01 = state_in[  383: 320];  // idx 5
  wire [63:0] s11 = state_in[  447: 384];  // idx 6
  wire [63:0] s21 = state_in[  511: 448];  // idx 7
  wire [63:0] s31 = state_in[  575: 512];  // idx 8
  wire [63:0] s41 = state_in[  639: 576];  // idx 9
  wire [63:0] s02 = state_in[  703: 640];  // idx 10
  wire [63:0] s12 = state_in[  767: 704];  // idx 11
  wire [63:0] s22 = state_in[  831: 768];  // idx 12
  wire [63:0] s32 = state_in[  895: 832];  // idx 13
  wire [63:0] s42 = state_in[  959: 896];  // idx 14
  wire [63:0] s03 = state_in[ 1023: 960];  // idx 15
  wire [63:0] s13 = state_in[ 1087:1024];  // idx 16
  wire [63:0] s23 = state_in[ 1151:1088];  // idx 17
  wire [63:0] s33 = state_in[ 1215:1152];  // idx 18
  wire [63:0] s43 = state_in[ 1279:1216];  // idx 19
  wire [63:0] s04 = state_in[ 1343:1280];  // idx 20
  wire [63:0] s14 = state_in[ 1407:1344];  // idx 21
  wire [63:0] s24 = state_in[ 1471:1408];  // idx 22
  wire [63:0] s34 = state_in[ 1535:1472];  // idx 23
  wire [63:0] s44 = state_in[ 1599:1536];  // idx 24

  // ----------------------------------------------------------------
  //  Theta: C[x] = XOR over y; D[x] = C[x-1] ^ rotl(C[x+1],1)
  // ----------------------------------------------------------------
  logic [63:0] C0, C1, C2, C3, C4;
  logic [63:0] D0, D1, D2, D3, D4;

  always_comb begin
    C0 = s00 ^ s01 ^ s02 ^ s03 ^ s04;
    C1 = s10 ^ s11 ^ s12 ^ s13 ^ s14;
    C2 = s20 ^ s21 ^ s22 ^ s23 ^ s24;
    C3 = s30 ^ s31 ^ s32 ^ s33 ^ s34;
    C4 = s40 ^ s41 ^ s42 ^ s43 ^ s44;

    D0 = C4 ^ rotl64(C1, 1);
    D1 = C0 ^ rotl64(C2, 1);
    D2 = C1 ^ rotl64(C3, 1);
    D3 = C2 ^ rotl64(C4, 1);
    D4 = C3 ^ rotl64(C0, 1);
  end

  // After theta: t{x}{y} = s{x}{y} ^ D{x}
  wire [63:0] t00 = s00 ^ D0;  wire [63:0] t01 = s01 ^ D0;
  wire [63:0] t02 = s02 ^ D0;  wire [63:0] t03 = s03 ^ D0;
  wire [63:0] t04 = s04 ^ D0;
  wire [63:0] t10 = s10 ^ D1;  wire [63:0] t11 = s11 ^ D1;
  wire [63:0] t12 = s12 ^ D1;  wire [63:0] t13 = s13 ^ D1;
  wire [63:0] t14 = s14 ^ D1;
  wire [63:0] t20 = s20 ^ D2;  wire [63:0] t21 = s21 ^ D2;
  wire [63:0] t22 = s22 ^ D2;  wire [63:0] t23 = s23 ^ D2;
  wire [63:0] t24 = s24 ^ D2;
  wire [63:0] t30 = s30 ^ D3;  wire [63:0] t31 = s31 ^ D3;
  wire [63:0] t32 = s32 ^ D3;  wire [63:0] t33 = s33 ^ D3;
  wire [63:0] t34 = s34 ^ D3;
  wire [63:0] t40 = s40 ^ D4;  wire [63:0] t41 = s41 ^ D4;
  wire [63:0] t42 = s42 ^ D4;  wire [63:0] t43 = s43 ^ D4;
  wire [63:0] t44 = s44 ^ D4;

  // ----------------------------------------------------------------
  //  Rho + Pi
  //  Pi: (x,y) -> (y, 2*x+3*y mod 5)
  //  Rho offsets from the spec for lane(x,y):
  //    (0,0)= 0  (1,0)= 1  (2,0)=62  (3,0)=28  (4,0)=27
  //    (0,1)=36  (1,1)=44  (2,1)= 6  (3,1)=55  (4,1)=20
  //    (0,2)= 3  (1,2)=10  (2,2)=43  (3,2)=25  (4,2)=39
  //    (0,3)=41  (1,3)=45  (2,3)=15  (3,3)=21  (4,3)= 8
  //    (0,4)=18  (1,4)= 2  (2,4)=61  (3,4)=56  (4,4)=14
  //
  //  Result named as p{dst_x}{dst_y} = rotl(t{src_x}{src_y}, rho)
  // ----------------------------------------------------------------
  wire [63:0] p00 = rotl64(t00,  0);  // (0,0)->(0,0)
  wire [63:0] p01 = rotl64(t30, 28);  // (3,0)->(0,1)
  wire [63:0] p02 = rotl64(t10,  1);  // (1,0)->(0,2)
  wire [63:0] p03 = rotl64(t40, 27);  // (4,0)->(0,3)
  wire [63:0] p04 = rotl64(t20, 62);  // (2,0)->(0,4)

  wire [63:0] p10 = rotl64(t11, 44);  // (1,1)->(1,0)
  wire [63:0] p11 = rotl64(t41, 20);  // (4,1)->(1,1)
  wire [63:0] p12 = rotl64(t21,  6);  // (2,1)->(1,2)
  wire [63:0] p13 = rotl64(t01, 36);  // (0,1)->(1,3)
  wire [63:0] p14 = rotl64(t31, 55);  // (3,1)->(1,4)

  wire [63:0] p20 = rotl64(t22, 43);  // (2,2)->(2,0)
  wire [63:0] p21 = rotl64(t02,  3);  // (0,2)->(2,1)
  wire [63:0] p22 = rotl64(t32, 25);  // (3,2)->(2,2)
  wire [63:0] p23 = rotl64(t12, 10);  // (1,2)->(2,3)
  wire [63:0] p24 = rotl64(t42, 39);  // (4,2)->(2,4)

  wire [63:0] p30 = rotl64(t33, 21);  // (3,3)->(3,0)
  wire [63:0] p31 = rotl64(t13, 45);  // (1,3)->(3,1)
  wire [63:0] p32 = rotl64(t43,  8);  // (4,3)->(3,2)
  wire [63:0] p33 = rotl64(t23, 15);  // (2,3)->(3,3)
  wire [63:0] p34 = rotl64(t03, 41);  // (0,3)->(3,4)

  wire [63:0] p40 = rotl64(t44, 14);  // (4,4)->(4,0)
  wire [63:0] p41 = rotl64(t24, 61);  // (2,4)->(4,1)
  wire [63:0] p42 = rotl64(t04, 18);  // (0,4)->(4,2)
  wire [63:0] p43 = rotl64(t34, 56);  // (3,4)->(4,3)
  wire [63:0] p44 = rotl64(t14,  2);  // (1,4)->(4,4)

  // ----------------------------------------------------------------
  //  Chi: out[x][y] = p[x][y] ^ (~p[(x+1)%5][y] & p[(x+2)%5][y])
  // ----------------------------------------------------------------
  wire [63:0] c00 = p00 ^ (~p10 & p20);
  wire [63:0] c01 = p01 ^ (~p11 & p21);
  wire [63:0] c02 = p02 ^ (~p12 & p22);
  wire [63:0] c03 = p03 ^ (~p13 & p23);
  wire [63:0] c04 = p04 ^ (~p14 & p24);

  wire [63:0] c10 = p10 ^ (~p20 & p30);
  wire [63:0] c11 = p11 ^ (~p21 & p31);
  wire [63:0] c12 = p12 ^ (~p22 & p32);
  wire [63:0] c13 = p13 ^ (~p23 & p33);
  wire [63:0] c14 = p14 ^ (~p24 & p34);

  wire [63:0] c20 = p20 ^ (~p30 & p40);
  wire [63:0] c21 = p21 ^ (~p31 & p41);
  wire [63:0] c22 = p22 ^ (~p32 & p42);
  wire [63:0] c23 = p23 ^ (~p33 & p43);
  wire [63:0] c24 = p24 ^ (~p34 & p44);

  wire [63:0] c30 = p30 ^ (~p40 & p00);
  wire [63:0] c31 = p31 ^ (~p41 & p01);
  wire [63:0] c32 = p32 ^ (~p42 & p02);
  wire [63:0] c33 = p33 ^ (~p43 & p03);
  wire [63:0] c34 = p34 ^ (~p44 & p04);

  wire [63:0] c40 = p40 ^ (~p00 & p10);
  wire [63:0] c41 = p41 ^ (~p01 & p11);
  wire [63:0] c42 = p42 ^ (~p02 & p12);
  wire [63:0] c43 = p43 ^ (~p03 & p13);
  wire [63:0] c44 = p44 ^ (~p04 & p14);

  // ----------------------------------------------------------------
  //  Iota — XOR round constant into lane(0,0)
  // ----------------------------------------------------------------
  logic [63:0] rc;
  always_comb rc = get_rc(round_idx);

  // Pack output in same order: idx = 5*y + x
  assign state_out = {
    c44, c34, c24, c14, c04,   // y=4: idx 24,23,22,21,20
    c43, c33, c23, c13, c03,   // y=3: idx 19,18,17,16,15
    c42, c32, c22, c12, c02,   // y=2: idx 14,13,12,11,10
    c41, c31, c21, c11, c01,   // y=1: idx  9, 8, 7, 6, 5
    c40, c30, c20, c10, c00 ^ rc  // y=0: idx  4, 3, 2, 1, 0
  };

endmodule
